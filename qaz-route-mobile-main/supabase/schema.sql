-- QazRoute: schema for the NEW Supabase project.
-- Run in Supabase Dashboard -> SQL Editor -> New query -> Run.

create table if not exists public.routes (
  id                 bigint generated by default as identity primary key,
  title              text    not null,
  location           text    not null,
  description        text    not null default '',
  preview_image_url  text    not null,
  route_images_urls  text[]  not null default '{}',
  completion_time    integer not null,          -- minutes
  distance           integer not null,          -- the app shows it as-is (team: metres or km?)
  path               text[]  not null,          -- each point "lat,lng", e.g. '43.1575,77.0590'
  created_at         timestamptz not null default now()
);

-- Everyone (even not logged in) can read the trail catalog.
alter table public.routes enable row level security;

drop policy if exists "routes are public" on public.routes;
create policy "routes are public"
  on public.routes for select
  to anon, authenticated
  using (true);

